const { chromium } = require('playwright'); const path = require('path'); const http = require('http'), fs = require('fs');
(async () => {
  const root = path.resolve(process.argv[2]); const pid = process.argv[3] || '2577';
  const srv = http.createServer((q, r) => { const f = path.join(root, decodeURIComponent(q.url.split('?')[0] === '/' ? '/index.html' : q.url.split('?')[0])); fs.readFile(f, (e, d) => { if (e) { r.statusCode = 404; return r.end('nf'); } r.setHeader('content-type', f.endsWith('.js') ? 'text/javascript' : f.endsWith('.css') ? 'text/css' : f.endsWith('.json') ? 'application/json' : 'text/html'); r.end(d); }); }).listen(8766);
  const browser = await chromium.launch(); const page = await browser.newPage({ viewport: { width: 1400, height: 1000 } });
  page.on('pageerror', e => console.log('PAGEERROR', e.message));
  await page.route(/^https?:\/\/[^/]*(sleeper|espn|corsproxy|allorigins|codetabs|api\.github\.com|raw\.githubusercontent)/, route => route.abort('failed'));
  await page.goto('http://localhost:8766/');
  await page.waitForFunction(() => document.querySelector('#recoList .item'), null, { timeout: 30000 });
  await page.waitForTimeout(800);
  console.log('HEAD:', await page.textContent('#leagueName'), '|', await page.textContent('#draftStatus'), '|', await page.textContent('#clock'));
  console.log('TURN:', (await page.textContent('#myTurn')).trim());
  console.log('TOP AVAIL:\n' + await page.$$eval('#availTable tbody tr', r => r.slice(0, 15).map(x => x.innerText.replace(/\t/g, ' | ')).join('\n')));
  await page.click('.tab[data-tab="picks"]'); await page.waitForTimeout(300);
  console.log('RECO:\n' + await page.$$eval('#recoList .item, #recoMore .item', r => r.map(x => x.innerText.replace(/\n/g, ' || ')).join('\n')));
  await page.screenshot({ path: 'real_picks.png' });
  await page.click('.tab[data-tab="league"]'); await page.waitForTimeout(200);
  console.log('LEAGUE:', (await page.textContent('#lgRoster')).replace(/\s+/g, ' '));
  console.log('SCORING:', (await page.textContent('#lgScoring')).replace(/\s+/g, ' '));
  await page.click('.tab[data-tab="draft"]'); await page.waitForTimeout(200);
  await page.click(`#availTable .name[data-pid="${pid}"]`); await page.waitForTimeout(1500);
  console.log('MODAL:', (await page.textContent('#modalBody')).replace(/\s+/g, ' ').slice(0, 2500));
  await page.screenshot({ path: 'real_modal.png', fullPage: true });
  console.log('DIAG:\n' + await page.textContent('#diag'));
  await browser.close(); srv.close();
})().catch(e => { console.error(e); process.exit(1); });
