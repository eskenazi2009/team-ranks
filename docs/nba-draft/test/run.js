const { chromium } = require('playwright');
const path = require('path');
const fx = require('./fixtures');
const http=require('http'),fs=require('fs');
(async () => {
  const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium/chrome-linux/chrome' }).catch(()=>chromium.launch());
  const page = await browser.newPage({ viewport: { width: 1400, height: 950 } });
  const unmatched = [];
  page.on('console', m => { if (m.type()==='error') console.log('CONSOLE', m.text()); });
  page.on('pageerror', e => console.log('PAGEERROR', e.message));
  await page.route(/sleeper|espn/, route => {
    const u = new URL(route.request().url()); const key = u.host + u.pathname;
    const hit = Object.keys(fx).filter(k => key === k || key.startsWith(k)).sort((a,b)=>b.length-a.length)[0];
    if (!hit) { unmatched.push(route.request().url()); return route.fulfill({ status: 404, body: 'nf' }); }
    route.fulfill({ status: 200, contentType: 'application/json', headers: { 'access-control-allow-origin': '*' }, body: JSON.stringify(fx[hit]) });
  });
  const root=path.resolve(process.argv[2]);
  const srv=http.createServer((q,r)=>{const f=path.join(root,decodeURIComponent(q.url.split('?')[0]==='/'?'/index.html':q.url.split('?')[0]));fs.readFile(f,(e,d)=>{if(e){r.statusCode=404;return r.end('nf');}r.setHeader('content-type',f.endsWith('.js')?'text/javascript':f.endsWith('.css')?'text/css':f.endsWith('.json')?'application/json':'text/html');r.end(d);});}).listen(8765);
  await page.goto('http://localhost:8765/');
  await page.waitForFunction(() => document.querySelector('#availTable tbody') && document.querySelector('#availTable tbody').children.length > 0, null, { timeout: 15000 });
  await page.waitForTimeout(500);
  console.log('DIAG0:\n' + await page.textContent('#diag'));
  console.log('STATUS:', await page.textContent('#draftStatus'), '|', await page.textContent('#clock'));
  console.log('TURN:', (await page.textContent('#myTurn')).trim());
  console.log('AVAIL rows:', await page.$$eval('#availTable tbody tr', r => r.map(x => x.innerText.replace(/\t/g,' | ')).slice(0,6).join('\n')));
  console.log('ROSTER:', (await page.textContent('#myRoster')).replace(/\s+/g,' '));
  await page.click('.tab[data-tab="picks"]'); await page.waitForTimeout(200);
  console.log('RECO:\n', await page.$$eval('#recoList .item', r => r.map(x => x.innerText).join('\n---\n')));
  await page.screenshot({ path: 'picks.png' });
  await page.click('.tab[data-tab="players"]'); await page.waitForTimeout(200);
  console.log('PLAYERS head:', await page.$eval('#plTable thead', t => t.innerText.replace(/\t/g,' | ')));
  console.log('PLAYERS rows:', await page.$$eval('#plTable tbody tr', r => r.map(x => x.innerText.replace(/\t/g,' | ')).slice(0,4).join('\n')));
  await page.click('#plPos .chip[data-p="C"]'); await page.waitForTimeout(100);
  console.log('PLAYERS filter C:', await page.$$eval('#plTable tbody tr', r => r.map(x => x.children[0].innerText).join(', ')));
  await page.click('.tab[data-tab="league"]'); await page.waitForTimeout(100);
  console.log('LEAGUE:', (await page.textContent('#lgRoster')).replace(/\s+/g,' '));
  await page.screenshot({ path: 'league.png' });
  await page.click('.tab[data-tab="draft"]'); await page.waitForTimeout(100);
  await page.screenshot({ path: 'draft.png' });
  await page.click('#availTable .name[data-pid="p5"]'); await page.waitForTimeout(800);
  console.log('MODAL:', (await page.textContent('#modalBody')).replace(/\s+/g,' ').slice(0,1500));
  await page.screenshot({ path: 'modal.png' });
  console.log('DIAG:\n' + await page.textContent('#diag'));
  console.log('UNMATCHED:', unmatched);
  await browser.close(); srv.close();
})().catch(e => { console.error(e); process.exit(1); });
